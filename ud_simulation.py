from pathlib import Path
import numpy as np
import pandas as pd

# =========================================================
# 1. 경로
# =========================================================

BASE_DIR = Path(__file__).resolve().parent
RESULT_DIR = BASE_DIR / "results"

ALLOCATION_PATH = RESULT_DIR / "ud_allocation_2025.csv"
OUTPUT_PATH = RESULT_DIR / "ud_simulation_2025.csv"


# =========================================================
# 2. 데이터 로드
# =========================================================

df = pd.read_csv(
    ALLOCATION_PATH,
    encoding="utf-8-sig"
)

print("========== 데이터 로드 ==========")
print(f"분석 조합: {len(df):,}개")


# =========================================================
# 3. UD 1대의 시간당 처리 가능 운행 계산
# =========================================================
# 기존 장애인콜택시의 차량 점유시간을
# UD택시도 동일하게 가진다고 가정
#
# 처리능력 = 60 / 평균 차량 점유시간

df["UD1대_시간당처리건수"] = (
    60 / df["평균차량점유시간_분"]
)

# 해당 지역에 배치된 UD 전체 처리능력

df["UD추가처리능력"] = (
    df["UD배치대수"]
    * df["UD1대_시간당처리건수"]
)


# =========================================================
# 4. 기존 공급 부족량 추정
# =========================================================
# 기본필요차량대수는 현재 수요를 처리하기 위해
# 필요한 차량 규모를 의미
#
# UD 투입 후 필요한 차량 규모에서
# UD 배치대수를 차감

df["UD투입후_필요차량"] = (
    df["기본필요차량대수"]
    - df["UD배치대수"]
).clip(lower=0)


# =========================================================
# 5. 공급 보완율
# =========================================================
# 필요한 차량 가운데 UD가 얼마나 보완하는지 계산

df["UD공급보완율_%"] = np.where(
    df["기본필요차량대수"] > 0,
    (
        df["UD배치대수"]
        / df["기본필요차량대수"]
        * 100
    ).clip(upper=100),
    0
)


# =========================================================
# 6. 대기시간 개선 시나리오
# =========================================================
# 실제 UD 운영 데이터가 없기 때문에
# 대기시간 감소를 직접 단정하지 않고
# 공급 보완율에 따른 시나리오로 추정
#
# 보수적: 공급 보완 효과의 25%
# 기준:   공급 보완 효과의 50%
# 적극적: 공급 보완 효과의 75%

SCENARIOS = {
    "보수적": 0.25,
    "기준": 0.50,
    "적극적": 0.75
}

for name, effect in SCENARIOS.items():

    reduction_ratio = (
        df["UD공급보완율_%"] / 100
        * effect
    )

    df[f"{name}_예상대기시간_분"] = (
        df["평균대기시간_분"]
        * (1 - reduction_ratio)
    )

    df[f"{name}_대기감소_분"] = (
        df["평균대기시간_분"]
        - df[f"{name}_예상대기시간_분"]
    )


# =========================================================
# 7. 기준 시나리오 개선율
# =========================================================

df["기준_대기개선율_%"] = np.where(
    df["평균대기시간_분"] > 0,
    (
        df["기준_대기감소_분"]
        / df["평균대기시간_분"]
        * 100
    ),
    0
)


# =========================================================
# 8. 결과 출력
# =========================================================

print("\n========== UD 투입 효과 TOP 30 ==========")

cols = [
    "요일",
    "승차시간대",
    "출발구",
    "배치유형",
    "UD배치대수",
    "평균대기시간_분",
    "기본필요차량대수",
    "UD공급보완율_%",
    "UD추가처리능력",
    "기준_예상대기시간_분",
    "기준_대기감소_분",
    "기준_대기개선율_%"
]

top = (
    df[df["UD배치대수"] > 0]
    .sort_values(
        "기준_대기감소_분",
        ascending=False
    )
    .head(30)
)

print(
    top[cols]
    .round(2)
    .to_string(index=False)
)


# =========================================================
# 9. 배치유형별 효과
# =========================================================

type_summary = (
    df[df["UD배치대수"] > 0]
    .groupby("배치유형")
    .agg(
        분석조합수=("배치유형", "size"),
        총UD배치=("UD배치대수", "sum"),
        평균기존대기시간=("평균대기시간_분", "mean"),
        평균공급보완율=("UD공급보완율_%", "mean"),
        평균기준예상대기시간=("기준_예상대기시간_분", "mean"),
        평균기준대기감소=("기준_대기감소_분", "mean"),
        평균추가처리능력=("UD추가처리능력", "mean")
    )
    .reset_index()
    .round(2)
)

print("\n========== 배치유형별 예상 효과 ==========")
print(type_summary.to_string(index=False))


# =========================================================
# 10. 전체 효과
# =========================================================

active = df[df["UD배치대수"] > 0].copy()

print("\n========== 전체 UD 동적배치 효과 ==========")

print(f"UD 투입 조합: {len(active):,}개")

print(
    "평균 기존 대기시간:",
    round(active["평균대기시간_분"].mean(), 2),
    "분"
)

print(
    "평균 공급 보완율:",
    round(active["UD공급보완율_%"].mean(), 2),
    "%"
)

print(
    "보수적 예상 대기시간:",
    round(active["보수적_예상대기시간_분"].mean(), 2),
    "분"
)

print(
    "기준 예상 대기시간:",
    round(active["기준_예상대기시간_분"].mean(), 2),
    "분"
)

print(
    "적극적 예상 대기시간:",
    round(active["적극적_예상대기시간_분"].mean(), 2),
    "분"
)


# =========================================================
# 11. 저장
# =========================================================

df.to_csv(
    OUTPUT_PATH,
    index=False,
    encoding="utf-8-sig"
)

print("\n========== 저장 완료 ==========")
print(OUTPUT_PATH)